    assert!(TaskOutcome::CompletedVerified.is_success(false));
    assert!(TaskOutcome::CompletedVerified.is_success(true));
    assert!(!TaskOutcome::CompletedUnverified.is_success(false));
    assert!(TaskOutcome::CompletedUnverified.is_success(true));
