/// Same inputs ⇒ same uuid; a different seq, index or parent ⇒ a
/// different uuid; the v5 name string is exactly `kian:spawn:<seq>:<index>`.
#[test]
fn spawn_uid_is_a_pure_function_of_parent_seq_and_index() {
    let a = spawn_uid(parent_session(), 7, 0);
    let b = spawn_uid(parent_session(), 7, 0);
    assert_eq!(a, b, "same inputs must derive the same uuid");
    assert_eq!(a.to_string(), GOLDEN_SPAWN_UID_SEQ7);
    // Different seq, different index, different parent: all distinct.
    assert_ne!(a, spawn_uid(parent_session(), 8, 0));
    assert_eq!(
        spawn_uid(parent_session(), 8, 0).to_string(),
        GOLDEN_SPAWN_UID_SEQ8
    );
    assert_ne!(a, spawn_uid(parent_session(), 7, 1));
    assert_eq!(
        spawn_uid(parent_session(), 7, 1).to_string(),
        GOLDEN_SPAWN_UID_INDEX1
    );
    assert_ne!(a, spawn_uid(other_parent_session(), 7, 0));
    assert_eq!(
        spawn_uid(other_parent_session(), 7, 0).to_string(),
        GOLDEN_SPAWN_UID_OTHER_NS
    );
    // The v5 name string is pinned byte-for-byte: re-derive with the
    // literal name and require identity.
    for (seq, index) in [(0u64, 0u32), (7, 0), (8, 0), (7, 1), (4_294_967_295, 9)] {
        let name = format!("kian:spawn:{seq}:{index}");
        assert_eq!(
            spawn_uid(parent_session(), seq, index),
            Uuid::new_v5(&parent_session().0, name.as_bytes()),
            "name string must be exactly {name}"
        );
    }
}

/// Pins P1's three derivation strings with independently generated
/// golden vectors; two calls never differ.
#[test]
fn child_thread_and_session_ids_are_derived_from_the_spawn_uid() {
    let uid = spawn_uid(parent_session(), 7, 0);
    let thread = child_thread_id(parent_session(), uid);
    let session = child_session_id(thread);
    assert_eq!(thread.to_string(), GOLDEN_THREAD_ID_SEQ7);
    assert_eq!(session.0.to_string(), GOLDEN_CHILD_SESSION_SEQ7);
    // Determinism: two calls never differ.
    assert_eq!(
        thread,
        child_thread_id(parent_session(), spawn_uid(parent_session(), 7, 0))
    );
    assert_eq!(
        session,
        child_session_id(child_thread_id(parent_session(), uid))
    );
    // The name strings are pinned byte-for-byte.
    assert_eq!(
        thread,
        Uuid::new_v5(&parent_session().0, format!("kian:thread:{uid}").as_bytes())
    );
    assert_eq!(session.0, Uuid::new_v5(&thread, "kian:session".as_bytes()));
    // The thread id is a function of the spawn uid: a different spawn
    // derives a different thread (and hence a different session).
    let uid8 = spawn_uid(parent_session(), 8, 0);
    assert_ne!(thread, child_thread_id(parent_session(), uid8));
    assert_ne!(
        session,
        child_session_id(child_thread_id(parent_session(), uid8))
    );
    // A v5-shaped uuid every time.
    assert_eq!(thread.get_version_num(), 5);
    assert_eq!(session.0.get_version_num(), 5);
}

/// For the same delegation, `spawn:<uid>` and `thread-report:<tid>`
/// both name one row and never collide across threads.
#[test]
fn report_key_is_1to1_with_the_legacy_key_under_derived_ids() {
    // One delegation: both keys name that delegation's single row.
    let identity = SpawnIdentity::derive(parent_session(), 7, "researcher", 3);
    let uid = spawn_uid(parent_session(), 7, 0);
    let thread = child_thread_id(parent_session(), uid);
    assert_eq!(report_key(&identity), format!("spawn:{uid}"));
    assert_eq!(legacy_report_key(thread), format!("thread-report:{thread}"));
    assert_eq!(task_input_key(thread), format!("thread:{thread}"));

    // 1:1 across a grid of delegations: the spawn-key family and the
    // legacy-key family are both injective and map onto each other, and
    // the two families never overlap (different prefixes).
    let mut spawn_keys = std::collections::HashSet::new();
    let mut legacy_keys = std::collections::HashSet::new();
    for seq in 0..64u64 {
        let uid = spawn_uid(parent_session(), seq, 0);
        let thread = child_thread_id(parent_session(), uid);
        spawn_keys.insert(format!("spawn:{uid}"));
        legacy_keys.insert(format!("thread-report:{thread}"));
    }
    assert_eq!(spawn_keys.len(), 64, "spawn keys collide across threads");
    assert_eq!(legacy_keys.len(), 64, "legacy keys collide across threads");
    assert!(
        spawn_keys.is_disjoint(&legacy_keys),
        "the two key families must never name the same row shape"
    );
    // Every pair is unique as a pair (no cross-thread collision).
    let pairs: std::collections::HashSet<(String, String)> = (0..64u64)
        .map(|seq| {
            let uid = spawn_uid(parent_session(), seq, 0);
            let thread = child_thread_id(parent_session(), uid);
            (format!("spawn:{uid}"), format!("thread-report:{thread}"))
        })
        .collect();
    assert_eq!(pairs.len(), 64);
}

/// The upgrade-safety hinge (pin P3): a legacy wrapper — no `spawn_uid`
/// string — keeps the legacy report key.
#[test]
fn legacy_wrapper_without_spawn_uid_keeps_the_legacy_report_key() {
    let uid = spawn_uid(parent_session(), 7, 0);
    let thread = child_thread_id(parent_session(), uid);
    let legacy_wrapper = json!({
        "thread_id": thread.to_string(),
        "task": {"role": "user", "content": "summarize the logs"},
    });
    assert_eq!(
        report_key_for(&legacy_wrapper, thread),
        legacy_report_key(thread)
    );
    // A wrapper carrying the identity takes the spawn key.
    let new_wrapper = json!({
        "thread_id": thread.to_string(),
        "task": {"role": "user", "content": "summarize the logs"},
        "spawn_uid": uid.to_string(),
        "task_id": thread.to_string(),
        "agent_def": "researcher",
        "agent_def_version": 3,
    });
    assert_eq!(report_key_for(&new_wrapper, thread), format!("spawn:{uid}"));
    // A non-string `spawn_uid` is not a carried identity: the legacy
    // key is the honest fallback, never a guess.
    let malformed = json!({"spawn_uid": 17});
    assert_eq!(
        report_key_for(&malformed, thread),
        legacy_report_key(thread)
    );
}

