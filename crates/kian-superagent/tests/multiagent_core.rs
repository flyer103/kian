/// §3.2:409-413: the target is `thread/started.parent` read from the
/// child's own stream — there is no ambient fallback and no Router id
/// anywhere in scope.
#[test]
fn join_target_is_read_from_the_child_stream_and_has_no_ambient_fallback() {
    let self_session = SessionId::new();
    let join_parent = sid("00000000-0000-0000-0000-0000000000aa");
    // A Router id that must never be consulted: it exists in the test
    // scope precisely to prove no ambient default leaks in.
    let ambient_router = sid("00000000-0000-0000-0000-0000000000ff");
    let events = child_stream(|_| {
        vec![ev(
            0,
            SessionId::new(),
            EventKind::ThreadStarted,
            json!({
                "thread_id": GOLDEN_THREAD_ID_SEQ7,
                "parent": join_parent.0.to_string(),
                "worker": self_session.0.to_string(),
                "pinned_version": 3,
                "task": {"role": "user", "content": {"thread_id": GOLDEN_THREAD_ID_SEQ7}},
            }),
        )]
    });
    assert_eq!(join_target(&events, self_session), Some(join_parent));
    assert_ne!(join_target(&events, self_session), Some(ambient_router));

    // A thread/started naming a different worker is not this session's
    // lineage: no target.
    let other_worker = SessionId::new();
    let events = child_stream(|_| {
        vec![ev(
            0,
            SessionId::new(),
            EventKind::ThreadStarted,
            json!({
                "thread_id": GOLDEN_THREAD_ID_SEQ7,
                "parent": join_parent.0.to_string(),
                "worker": other_worker.0.to_string(),
                "pinned_version": 3,
                "task": {},
            }),
        )]
    });
    assert_eq!(join_target(&events, self_session), None);

    // A stream with no readable thread/started.parent: None — the
    // caller must refuse (F17), never fall back.
    let events = child_stream(|_| {
        vec![ev(
            0,
            SessionId::new(),
            EventKind::InputAdmitted,
            json!({"content": {}}),
        )]
    });
    assert_eq!(join_target(&events, self_session), None);
    assert_eq!(join_target(&[], self_session), None);
}

