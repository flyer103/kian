/// §6.2 row 5: the `budget_exhausted` class derives `budget_exhausted`,
/// with or without the completion carrier.
#[test]
fn budget_exhausted_class_derives_budget_exhausted() {
    // With the completion carrier (the loop reached its completion
    // step before the budget ended the session).
    let events = child_stream(|_| {
        vec![
            turn_end_error_event("budget_exhausted"),
            ev(
                0,
                SessionId::new(),
                EventKind::ThreadCompleted,
                json!({
                    "thread_id": GOLDEN_THREAD_ID_SEQ7,
                    "status": "failed",
                    "summary": {"text": "turn budget exhausted"},
                }),
            ),
        ]
    });
    assert_eq!(
        derive_outcome(&events, None),
        Some(TaskOutcome::BudgetExhausted)
    );
    // Without the completion carrier: session/ended{failed} under the
    // budget class carries the same outcome (row 5's second half).
    let events = child_stream(|_| {
        vec![
            turn_end_error_event("budget_exhausted"),
            session_ended(EndReason::Failed),
        ]
    });
    assert_eq!(
        derive_outcome(&events, None),
        Some(TaskOutcome::BudgetExhausted)
    );
    // The classes are distinct: empty_response never reads as budget.
    let events = child_stream(|_| {
        vec![
            turn_end_error_event("empty_response"),
            session_ended(EndReason::Failed),
        ]
    });
    // No completion ⇒ not row 3; no budget class ⇒ not row 5:
    // outstanding, never a guess (§6.3).
    assert_eq!(derive_outcome(&events, None), None);
}

/// §6.2 rows 6-7: `child_timeout` ⇒ `stalled`, any other requester ⇒
/// `interrupted`; and `stalled != failed` (M6).
#[test]
fn interrupt_by_child_timeout_derives_stalled_and_explicit_interrupt_derives_interrupted() {
    let child_timeout = child_stream(|_| {
        vec![
            control_interrupt_event("child_timeout"),
            session_ended(EndReason::Interrupted),
        ]
    });
    assert_eq!(
        derive_outcome(&child_timeout, None),
        Some(TaskOutcome::Stalled)
    );
    // M6: stalled is a timing fact, never a failure.
    assert_ne!(TaskOutcome::Stalled, TaskOutcome::Failed);
    assert!(!TaskOutcome::Stalled.is_success(true));

    let explicit = child_stream(|_| {
        vec![
            control_interrupt_event("0f9c2a11-3b4d-4e5f-8a6b-7c8d9e0f1a2b"),
            session_ended(EndReason::Interrupted),
        ]
    });
    assert_eq!(
        derive_outcome(&explicit, None),
        Some(TaskOutcome::Interrupted)
    );
    assert_ne!(TaskOutcome::Interrupted, TaskOutcome::Stalled);
    assert_ne!(TaskOutcome::Interrupted, TaskOutcome::Failed);

    // An interrupt that ended nothing is outstanding: the row's carrier
    // is the pair, not the intent alone.
    let unconsumed = child_stream(|_| vec![control_interrupt_event("child_timeout")]);
    assert_eq!(derive_outcome(&unconsumed, None), None);

    // A stale (audit-only) interrupt never counts: the last non-stale
    // requester decides.
    let stale_then_real = child_stream(|_| {
        vec![
            {
                let mut e = control_interrupt_event("child_timeout");
                e.bytes["stale"] = json!(true);
                e
            },
            control_interrupt_event("ops"),
            session_ended(EndReason::Interrupted),
        ]
    });
    assert_eq!(
        derive_outcome(&stale_then_real, None),
        Some(TaskOutcome::Interrupted)
    );
}

/// §6.2 row 9 (§6.2.1:676-682): a report row with `state:"waiting"`
/// and no completion and no end ⇒ `input_required`.
#[test]
fn a_waiting_report_derives_input_required_without_any_completion() {
    let thread = child_thread_id(parent_session(), spawn_uid(parent_session(), 7, 0));
    let events = child_stream(|_| {
        vec![ev(
            0,
            SessionId::new(),
            EventKind::TurnEnd,
            json!({"iteration": 2, "outcome": "final_answer"}),
        )]
    });
    let report = waiting_report(thread, Some(ReportState::Waiting));
    assert_eq!(
        derive_outcome(&events, Some(&report)),
        Some(TaskOutcome::InputRequired)
    );
    // Only "waiting" is the row's carrier: a ready report with no
    // completion is outstanding, not input_required.
    let ready = waiting_report(thread, Some(ReportState::Ready));
    assert_eq!(derive_outcome(&events, Some(&ready)), None);
    // No report at all: outstanding.
    assert_eq!(derive_outcome(&events, None), None);
    // An ended session never reports input_required (the child is not
    // live-and-resumable anymore).
    let events = child_stream(|_| vec![session_ended(EndReason::Completed)]);
    assert_eq!(derive_outcome(&events, Some(&report)), None);
}

