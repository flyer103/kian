fn ev(seq: u64, session: SessionId, kind: EventKind, bytes: Value) -> Event {
    Event {
        seq,
        session,
        epoch: Epoch(1),
        ts: 1_700_000_000_000 + seq,
        kind,
        bytes,
        version: 0,
    }
}

fn child_stream(bytes: impl FnOnce(u64) -> Vec<Event>) -> Vec<Event> {
    let session = SessionId::new();
    let mut events = vec![ev(1, session, EventKind::SessionCreated, json!({}))];
    for (i, mut e) in bytes(2).into_iter().enumerate() {
        e.seq = u64::try_from(i).unwrap() + 2;
        events.push(e);
    }
    events
}

