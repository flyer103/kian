/// The pure decision: `thread/completed` present ⇒ `ReAdmit` with the
/// pin-P3 key and the byte-stable pin-P6 report; absent ⇒ `Nothing`.
#[test]
fn reconciliation_decides_re_admit_when_the_completion_exists_without_a_row() {
    let uid = spawn_uid(parent_session(), 7, 0);
    let thread = child_thread_id(parent_session(), uid);
    let wrapper = json!({
        "thread_id": thread.to_string(),
        "task": {"role": "user", "content": "summarize the logs"},
        "spawn_uid": uid.to_string(),
        "task_id": thread.to_string(),
        "agent_def": "researcher",
        "agent_def_version": 3,
    });
    let summary = json!({"role": "assistant", "content": "done: 3 files"});

    // With a completion and a committed worker verdict: ReAdmit with
    // the spawn key and the full class-C report.
    let events = child_stream(|_| {
        vec![
            worker_verdict_event(true),
            ev(
                0,
                SessionId::new(),
                EventKind::ThreadCompleted,
                json!({
                    "thread_id": thread.to_string(),
                    "status": "completed",
                    "summary": summary.clone(),
                }),
            ),
        ]
    });
    match reconcile_completion(&events, &wrapper, thread, "completed", &summary) {
        Reconcile::ReAdmit { key, report } => {
            assert_eq!(key, format!("spawn:{uid}"), "the pin-P3 key");
            assert_eq!(
                report,
                json!({
                    "thread_id": thread.to_string(),
                    "status": "completed",
                    "summary": summary,
                    "spawn_uid": uid.to_string(),
                    "task_id": thread.to_string(),
                    "contract": {
                        "passed": true,
                        "errors": [],
                    },
                })
            );
        }
        other => panic!("expected ReAdmit, got {other:?}"),
    }

    // No gate verdict committed: the report omits `contract` entirely
    // (absent, never null — pin P6's "iff").
    let events = child_stream(|_| {
        vec![ev(
            0,
            SessionId::new(),
            EventKind::ThreadCompleted,
            json!({
                "thread_id": thread.to_string(),
                "status": "completed",
                "summary": summary.clone(),
            }),
        )]
    });
    match reconcile_completion(&events, &wrapper, thread, "completed", &summary) {
        Reconcile::ReAdmit { key, report } => {
            assert_eq!(key, format!("spawn:{uid}"));
            assert!(report.get("contract").is_none());
            assert_eq!(report.get("spawn_uid"), Some(&json!(uid.to_string())));
            assert_eq!(report.get("task_id"), Some(&json!(thread.to_string())));
        }
        other => panic!("expected ReAdmit, got {other:?}"),
    }

    // A failed verdict commits `contract` with the failed check names.
    let events = child_stream(|_| {
        vec![
            worker_verdict_event(false),
            ev(
                0,
                SessionId::new(),
                EventKind::ThreadCompleted,
                json!({
                    "thread_id": thread.to_string(),
                    "status": "failed",
                    "summary": summary.clone(),
                }),
            ),
        ]
    });
    match reconcile_completion(&events, &wrapper, thread, "failed", &summary) {
        Reconcile::ReAdmit { report, .. } => {
            assert_eq!(
                report.get("contract"),
                Some(&json!({
                    "passed": false,
                    "errors": ["no_error_tool_result_tail"],
                }))
            );
        }
        other => panic!("expected ReAdmit, got {other:?}"),
    }

    // Byte-stable: the same events derive the same report twice.
    let a = reconcile_completion(&events, &wrapper, thread, "failed", &summary);
    let b = reconcile_completion(&events, &wrapper, thread, "failed", &summary);
    assert_eq!(a, b);

    // A legacy wrapper (no spawn_uid): the legacy key and the legacy
    // triple — the migration hinge holds inside reconciliation too.
    let legacy_wrapper = json!({
        "thread_id": thread.to_string(),
        "task": {"role": "user", "content": "summarize the logs"},
    });
    match reconcile_completion(&events, &legacy_wrapper, thread, "failed", &summary) {
        Reconcile::ReAdmit { key, report } => {
            assert_eq!(key, legacy_report_key(thread));
            assert!(report.get("spawn_uid").is_none());
            assert!(report.get("task_id").is_none());
        }
        other => panic!("expected ReAdmit, got {other:?}"),
    }

    // No completion on the stream: Nothing — today's early return.
    let events = child_stream(|_| {
        vec![ev(
            0,
            SessionId::new(),
            EventKind::TurnEnd,
            json!({"iteration": 1, "outcome": "final_answer"}),
        )]
    });
    assert_eq!(
        reconcile_completion(&events, &wrapper, thread, "completed", &summary),
        Reconcile::Nothing
    );
}
