/// §5.3:585: Live and NeverStarted children hold the parent; a
/// Released child does not.
#[test]
fn holding_children_counts_only_children_that_still_hold_the_parent() {
    let w1 = SessionId::new();
    let w2 = SessionId::new();
    let w3 = SessionId::new();
    let parent = SessionId::new();
    let started = |worker: SessionId| {
        ev(
            0,
            parent,
            EventKind::ThreadStarted,
            json!({
                "thread_id": Uuid::new_v4().to_string(),
                "parent": parent.0.to_string(),
                "worker": worker.0.to_string(),
                "pinned_version": 1,
                "task": {},
            }),
        )
    };
    let events = vec![
        started(w1),
        ev(0, parent, EventKind::TurnStart, json!({"iteration": 1})),
        started(w2),
        started(w3),
    ];
    let liveness = |s: SessionId| {
        if s == w1 {
            ThreadLiveness::Live
        } else if s == w2 {
            ThreadLiveness::NeverStarted
        } else {
            ThreadLiveness::Released
        }
    };
    assert_eq!(holding_children(&events, &liveness), 2);
    // Everything released: nobody holds the parent.
    let all_released = |_: SessionId| ThreadLiveness::Released;
    assert_eq!(holding_children(&events, &all_released), 0);
    // An empty parent stream: zero.
    assert_eq!(holding_children(&[], &liveness), 0);
    // The same worker named twice (a takeover re-append) still holds
    // exactly one slot.
    let events = vec![started(w1), started(w1)];
    assert_eq!(holding_children(&events, &liveness), 1);
}

/// §5.3 / §8.3:864: the refusal names the bound and the current count —
/// never truncation, never a silent drop.
#[test]
fn cap_refusal_names_the_bound_and_the_current_count() {
    let limits = MultiagentLimits {
        max_children: 4,
        max_depth: 1,
        child_timeout_ms: 900_000,
    };
    // At the cap: the fifth spawn refuses, naming bound + counts.
    assert_eq!(
        cap_refusal(&limits, 4, 0),
        Some(CapRefusal {
            bound: "max_children",
            current: 4,
            max: 4,
        })
    );
    // Never truncates: the current count is reported honestly even
    // when it exceeds the max.
    assert_eq!(
        cap_refusal(&limits, 5, 0),
        Some(CapRefusal {
            bound: "max_children",
            current: 5,
            max: 4,
        })
    );
    // Under both bounds: permitted (None — no refusal).
    assert_eq!(cap_refusal(&limits, 3, 0), None);
    assert_eq!(cap_refusal(&limits, 0, 0), None);
    // The depth bound: a child orchestrator at depth 1 with
    // max_depth 1 refuses to spawn (the would-be child needs a hop).
    assert_eq!(
        cap_refusal(&limits, 0, 1),
        Some(CapRefusal {
            bound: "max_depth",
            current: 1,
            max: 1,
        })
    );
    // §5.4's order: depth is checked before max_children, so a spawn
    // violating both names max_depth.
    assert_eq!(
        cap_refusal(&limits, 9, 1),
        Some(CapRefusal {
            bound: "max_depth",
            current: 1,
            max: 1,
        })
    );
    // A raised depth admits deeper chains.
    let raised = MultiagentLimits {
        max_children: 4,
        max_depth: 2,
        child_timeout_ms: 900_000,
    };
    assert_eq!(cap_refusal(&raised, 0, 1), None);
    assert_eq!(
        cap_refusal(&raised, 0, 2),
        Some(CapRefusal {
            bound: "max_depth",
            current: 2,
            max: 2,
        })
    );
}

/// Item 7: `max_depth == 0` and `child_timeout_ms == 0` are refused;
/// `max_children == 0` (a leaf-only parent) is legal.
#[test]
fn limits_validation_refuses_zero_depth_and_zero_timeout_but_allows_a_leaf_parent() {
    use kian_superagent::{DEFAULT_CHILD_TIMEOUT_MS, DEFAULT_MAX_CHILDREN, DEFAULT_MAX_DEPTH};
    // The §5.3:585-589 defaults.
    assert_eq!(DEFAULT_MAX_CHILDREN, 4);
    assert_eq!(DEFAULT_MAX_DEPTH, 1);
    assert_eq!(DEFAULT_CHILD_TIMEOUT_MS, 900_000);

    // A leaf-only parent is an explicit, legal policy.
    let leaf = MultiagentLimits {
        max_children: 0,
        max_depth: 1,
        child_timeout_ms: 900_000,
    };
    assert_eq!(leaf.validate(), Ok(()));
    // The defaults validate.
    let defaults = MultiagentLimits {
        max_children: DEFAULT_MAX_CHILDREN,
        max_depth: DEFAULT_MAX_DEPTH,
        child_timeout_ms: DEFAULT_CHILD_TIMEOUT_MS,
    };
    assert_eq!(defaults.validate(), Ok(()));

    // Zero depth: refused, the key named.
    let zero_depth = MultiagentLimits {
        max_children: 4,
        max_depth: 0,
        child_timeout_ms: 900_000,
    };
    let err = zero_depth.validate().expect_err("zero depth must refuse");
    assert!(err.contains("max_depth"), "error must name the key: {err}");

    // Zero timeout: refused, the key named.
    let zero_timeout = MultiagentLimits {
        max_children: 4,
        max_depth: 1,
        child_timeout_ms: 0,
    };
    let err = zero_timeout
        .validate()
        .expect_err("zero timeout must refuse");
    assert!(
        err.contains("child_timeout_ms"),
        "error must name the key: {err}"
    );
}

